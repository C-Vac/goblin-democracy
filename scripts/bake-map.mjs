#!/usr/bin/env node
/**
 * Cut a local copy of the Mudwick map for development, and (once) the land mask.
 *
 *   SHARP_FROM=<file beside a sharp install> node scripts/bake-map.mjs <map base image> v55
 *
 * Writes public/map-local/mudwick.webp (gitignored: the map is never committed; the page fetches the
 * live map from GoblinLife.org's CDN, see src/mapArt.ts, and uses this copy only in development when
 * the CDN has none). Without IMAGE_ONLY it also writes engine/mudwickMask.ts, the land mask the engine
 * uses to put polling places on land. The current mask is cut from the finished map, v55 (its 2048 px
 * base from the CDN manifest). The map, its districts and its names belong to GoblinLife.org's map room. sharp is not a
 * dependency of this repo: point SHARP_FROM at any file whose folder can resolve it.
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [src, ver] = process.argv.slice(2);
if (!src || !ver) { console.error('usage: bake-map.mjs <bake.webp> <version>'); process.exit(2); }
const require = createRequire(process.env.SHARP_FROM || import.meta.url);
const sharp = require('sharp');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const meta = await sharp(src, { limitInputPixels: false }).metadata();
const W = Math.min(2048, meta.width), H = Math.round((meta.height / meta.width) * W);
fs.mkdirSync(path.join(root, 'public/map-local'), { recursive: true });
await sharp(src, { limitInputPixels: false }).resize(W, H).webp({ quality: 62, effort: 6 }).toFile(path.join(root, 'public/map-local/mudwick.webp'));

if (process.env.IMAGE_ONLY) { console.log(`map ${W}x${H} -> public/map-local/mudwick.webp (mask kept)`); process.exit(0); }

// Land mask: MW x MH samples. Water is the teal sea and the lakes; the cartouche scroll is never land.
const MW = 400, MH = Math.round((meta.height / meta.width) * MW);
const { data } = await sharp(src, { limitInputPixels: false }).resize(MW, MH, { kernel: 'cubic' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const bits = new Uint8Array(Math.ceil((MW * MH) / 8));
let land = 0;
for (let y = 0; y < MH; y++) for (let x = 0; x < MW; x++) {
  const k = (y * MW + x) * 3, r = data[k], g = data[k + 1], b = data[k + 2];
  const water = g - r > 18 && b - r > 0 && b > g * 0.65;
  const cartouche = x / MW > 0.725 && y / MH > 0.7;
  const parchment = r > 170 && g > 150 && b > 110 && r - b < 70 && r - b > 15 && x / MW > 0.7 && y / MH > 0.68;
  if (!water && !cartouche && !parchment) { bits[(y * MW + x) >> 3] |= 1 << ((y * MW + x) & 7); land++; }
}
const b64 = Buffer.from(bits).toString('base64');
const ts = `/**
 * Land mask for the Mudwick map, bake ${ver} (generated by scripts/bake-map.mjs; do not edit).
 * ${MW} x ${MH} samples, row-major, one bit per sample, 1 = land. The cartouche counts as sea.
 */
export const MASK_VERSION = '${ver}';
export const MASK_W = ${MW};
export const MASK_H = ${MH};
export const MASK_B64 = '${b64}';
`;
fs.writeFileSync(path.join(root, 'engine/mudwickMask.ts'), ts);

// A debug view: land white, sea black.
const dbg = Buffer.alloc(MW * MH);
for (let i = 0; i < MW * MH; i++) dbg[i] = bits[i >> 3] & (1 << (i & 7)) ? 255 : 0;
if (process.env.MASK_PREVIEW) await sharp(dbg, { raw: { width: MW, height: MH, channels: 1 } }).png().toFile(process.env.MASK_PREVIEW);
console.log(`map ${W}x${H} -> public/map-local/mudwick.webp; mask ${MW}x${MH}, land ${((land / (MW * MH)) * 100).toFixed(1)}%`);
