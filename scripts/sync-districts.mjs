#!/usr/bin/env node
/**
 * Copy the map room's district outlines into the engine.
 *
 *   node scripts/sync-districts.mjs ~/rooms/map/plan/districts-draft.json
 *
 * Writes engine/mudwickDistricts.ts. The map room owns the file and its schema: districts are whole
 * blocks of the street grid, one piece each, meeting along streets and never overlapping. Coordinates
 * are % of the 8256 x 4608 bake. Dwellings per street block (`settled`) say where people live. The simulator keeps its own populations, species mix and briefs in
 * engine/mudwick.ts; only names, kinds, outlines, label points, neighbours and dwelling counts come from here.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const [src] = process.argv.slice(2);
if (!src) { console.error('usage: sync-districts.mjs <districts-draft.json>'); process.exit(2); }
const d = JSON.parse(fs.readFileSync(src, 'utf8'));
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let commit = 'unknown';
try { commit = execFileSync('git', ['log', '-1', '--format=%h', '--', path.basename(src)], { cwd: path.dirname(src) }).toString().trim() || commit; } catch { /* not a git checkout */ }

const r = (v) => Math.round(v * 1000) / 1000;
// Street block (i, j) spans c = y - x/2 in C0 + [i, i+1]*S and d = y + x/2 in D0 + [j, j+1]*S (map px).
const { S, C0, D0 } = d.lattice;
const W = 8256, H = 4608;
const blockCentre = (i, j) => {
  const c = C0 + (i + 0.5) * S, dd = D0 + (j + 0.5) * S;
  return [r(((dd - c) / W) * 100), r((((c + dd) / 2) / H) * 100)];
};
const inPoly = ([x, y], poly) => {
  let inside = false;
  for (let a = 0, b = poly.length - 1; a < poly.length; b = a++) {
    const [xa, ya] = poly[a], [xb, yb] = poly[b];
    if ((ya > y) !== (yb > y) && x < ((xb - xa) * (y - ya)) / (yb - ya) + xa) inside = !inside;
  }
  return inside;
};
const shapes = {};
for (const id of Object.keys(d.names)) {
  const loops = d.polys[id];
  if (!loops?.length) throw new Error(`district ${id} has no outline`);
  shapes[id] = {
    name: d.names[id],
    kind: d.kinds[id],
    poly: loops[0].map(([x, y]) => [r(x), r(y)]),
    label: d.label[id].map(r),
    adjacent: d.adjacent?.[id] ?? [],
    homes: d.homes?.[id] ?? 0,
    settled: (d.settled?.[id] ?? []).map(([i, j, n]) => [...blockCentre(i, j), n]),
  };
  const outside = shapes[id].settled.filter(([x, y]) => !inPoly([x, y], shapes[id].poly)).length;
  if (outside) console.warn(`${id}: ${outside} settled block centre(s) fall outside its outline`);
}
const ts = `/**
 * District outlines from the map room (generated by scripts/sync-districts.mjs from
 * ${path.basename(src)} @ ${commit}; do not edit). % of the 8256 x 4608 bake. The owner signed off
 * names and edges on 2026-11-14; dwelling counts follow the latest bake.
 */
export const DISTRICT_SOURCE = '${path.basename(src)}@${commit}';\nexport const SETTLED_FROM = ${JSON.stringify(d.settledFrom ?? '')};
export interface DistrictShape {
  name: string;
  kind: 'city' | 'country' | 'base';
  poly: Array<[number, number]>;
  label: [number, number];
  adjacent: string[];
  /** Dwellings the bake draws: a relative weight, not a population. */
  homes: number;
  /** Dwellings per street block: [x%, y%, count] at each block's centre. */
  settled: Array<[number, number, number]>;
}
export const SHAPES: Record<string, DistrictShape> = ${JSON.stringify(shapes)};
`;
fs.writeFileSync(path.join(root, 'engine/mudwickDistricts.ts'), ts);
console.log(`${Object.keys(shapes).length} districts from ${path.basename(src)}@${commit}`);
